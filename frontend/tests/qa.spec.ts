import { test, expect } from '@playwright/test';

test('質問CRUD・回答・入力修正・直接URL', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Questions', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'new', exact: true }).click();
  await page.getByRole('button', { name: 'Create Question' }).click();
  await expect(page.getByRole('alert')).toContainText("Title can't be blank");
  await page.getByLabel('Title', { exact: true }).fill('移行テスト');
  await page.getByLabel('Name', { exact: true }).fill('投稿者');
  await page.getByLabel('Content', { exact: true }).fill('あいうえ');
  await page.getByRole('button', { name: 'Create Question' }).click();
  await expect(page.getByRole('alert')).toContainText('minimum is 5');
  await expect(page.getByLabel('Title', { exact: true })).toHaveValue('移行テスト');
  await page.getByLabel('Content', { exact: true }).fill('あいうえお');
  await page.getByRole('button', { name: 'Create Question' }).click();
  await expect(page).toHaveURL(/\/questions\/\d+$/);
  const detail = page.url();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Show', exact: true })).toBeVisible();
  // Empty answers are permitted by the original model.
  await page.getByRole('button', { name: 'Create Answer' }).click();
  await expect(page.getByRole('button', { name: 'Destroy answer' })).toHaveCount(1);
  page.once('dialog', dialog => dialog.dismiss());
  await page.getByRole('button', { name: 'Destroy answer' }).click();
  await expect(page.getByRole('button', { name: 'Destroy answer' })).toHaveCount(1);
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Destroy answer' }).click();
  await expect(page.getByRole('button', { name: 'Destroy answer' })).toHaveCount(0);
  await page.getByLabel('Name', { exact: true }).fill('回答者');
  await page.getByLabel('Content', { exact: true }).fill('回答本文');
  await page.getByRole('button', { name: 'Create Answer' }).click();
  await expect(page.getByText('Content: 回答本文', { exact: true })).toBeVisible();
  await page.goto(`${detail}/edit`);
  await expect(page.getByLabel('Title', { exact: true })).toHaveValue('移行テスト');
  await page.getByLabel('Title', { exact: true }).fill('更新した質問');
  await page.getByRole('button', { name: 'Update Question' }).click();
  await expect(page).toHaveURL(detail);
  await page.getByRole('link', { name: 'top', exact: true }).click();
  await expect(page.getByRole('cell', { name: '更新した質問', exact: true })).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Destroy', exact: true }).click();
  await expect(page.getByRole('cell', { name: '更新した質問', exact: true })).toHaveCount(0);
  await page.goto(detail);
  await expect(page.getByRole('alert')).toContainText('対象のデータが見つかりません');
});

test('通信失敗と保存失敗でも入力を保持し、再試行できる', async ({ page }) => {
  await page.goto('/questions/new');
  await page.getByLabel('Title').fill('保持する題名');
  await page.getByLabel('Name').fill('名前');
  await page.getByLabel('Content').fill('本文を保持します');
  await page.route('**/api/questions', route => route.abort());
  await page.getByRole('button', { name: 'Create Question' }).click();
  await expect(page.getByRole('alert')).toContainText('通信に失敗');
  await expect(page.getByLabel('Title')).toHaveValue('保持する題名');
  await page.unroute('**/api/questions');
  await page.route('**/api/questions', route => route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: 'internal_server_error', description: '保存に失敗' }) }));
  await page.getByRole('button', { name: 'Create Question' }).click();
  await expect(page.getByRole('alert')).toContainText('保存に失敗');
  await expect(page.getByLabel('Content')).toHaveValue('本文を保持します');
  await page.unroute('**/api/questions');
  await page.getByRole('button', { name: 'Create Question' }).click();
  await expect(page).toHaveURL(/\/questions\/\d+$/);
  await page.route('**/api/questions', route => route.abort());
  await page.goto('/questions');
  await expect(page.getByRole('alert')).toContainText('通信に失敗');
  await page.unroute('**/api/questions');
  await page.getByRole('button', { name: 'Retry' }).click();
  await expect(page.getByRole('cell', { name: '保持する題名', exact: true })).toBeVisible();
});
